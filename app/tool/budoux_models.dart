// Writes lib/core/design/phrase_models.dart: BudouX's models for Chinese and
// Japanese, which BalancedText uses to break lines between phrases.
//
//   npm pack budoux@0.9.2 && tar -xzf budoux-0.9.2.tgz
//   cd app && dart run tool/budoux_models.dart <path to package/src/data/models>
//
// BudouX (https://github.com/google/budoux) is Google's, under the Apache
// License 2.0; the models are its data, copied as they are.
import 'dart:convert';
import 'dart:io';

/// The BudouX release the models come from; the usage above fetches it.
const version = '0.9.2';

const models = {'zh-hant': 'zhHant', 'zh-hans': 'zhHans', 'ja': 'ja'};

void main(List<String> args) {
  final out = StringBuffer()
    ..writeln('// Generated by tool/budoux_models.dart from BudouX $version')
    ..writeln('// (https://github.com/google/budoux): its models for breaking lines between')
    ..writeln('// phrases. Copyright 2021 Google LLC, Apache License 2.0')
    ..writeln('// (http://www.apache.org/licenses/LICENSE-2.0). Do not edit.')
    ..writeln('// dart format off')
    ..writeln();
  String quote(String s) => jsonEncode(s).replaceAll(r'$', r'\$');
  for (final MapEntry(key: file, value: name) in models.entries) {
    final source = File('${args.single}/$file.ts').readAsStringSync();
    final json =
        jsonDecode(source.substring(source.indexOf('{"'), source.lastIndexOf('}') + 1)) as Map<String, dynamic>;
    out.writeln('const $name = <String, Map<String, int>>{');
    for (final MapEntry(key: feature, value: weights) in json.entries) {
      out.write('  ${quote(feature)}: {');
      out.write((weights as Map<String, dynamic>).entries.map((e) => '${quote(e.key)}: ${e.value}').join(', '));
      out.writeln('},');
    }
    out.writeln('};');
    out.writeln();
  }
  File('lib/core/design/phrase_models.dart').writeAsStringSync(out.toString());
  stdout.writeln('Wrote ${models.length} models.');
}
